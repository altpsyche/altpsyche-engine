/**
 * Every corpus preset carries an asserted `cost()` (item 23). Where
 * [tests/cost.test.ts](./cost.test.ts) pins the arithmetic on hand-built frames
 * — one field at a time, on a frame as small as that field needs — this pins the
 * whole metric on the frames the package actually measures itself against, so a
 * change that adds a pass, a pipeline switch, an attachment store or a transient
 * byte to any preset fails here until the number below is updated deliberately.
 * That is the load-bearing property of decision 9: the cost is asserted in CI, on
 * any machine, because it is a fact about a graph's structure rather than
 * anything a card does.
 *
 * The numbers are not a claim about any hardware. They are what `cost()` returns
 * for each preset's graph at the corpus size, produced by running `cost()` in the
 * node suite; a card never enters, and none of these figures is a timing.
 */

/** The size the corpus declares its uniforms at (`u_resolution` is [800, 600]
 * throughout `fixtures/capability-fixtures.ts`), so a frame-sized transient is
 * resolved against the same window the preset is authored for. */
const SIZE = { width: 800, height: 600 };

/** The corpus frame for a preset, assembled the way a loader assembles one: the
 * description off its own source, the generated bytes rekeyed from the address
 * they are fetched by to the resource that reads them, and the uniforms the entry
 * declares. No block is passed because `cost()` reads none — it counts structure,
 * and the uniform block is a layout fact the metric never touches. */
function corpusFrame(id: string) {
  const one = CAPABILITY_FIXTURES.find((fixture) => fixture.id === id)!;
  const { description, code, generated } = loadFixture(id);
  const bytes = new Map<string, Uint8Array<ArrayBuffer>>();
  for (const resource of description.resources) {
    if (!('source' in resource) || !resource.source) continue;
    bytes.set(resource.name, generated.get(resource.source)!);
  }
  const texts = new Map(description.documents.map((document) => [document.name, code]));
  const uniforms = one.uniforms.map((uniform) => ({ name: uniform.name, type: uniform.type }));
  return assembleFrame(id, description, texts, bytes, uniforms);
}

