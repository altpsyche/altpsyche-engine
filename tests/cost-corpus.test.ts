describe('the corpus costs', () => {
  it('has an asserted cost for every preset and no cost for a preset that left', () => {
    // Adding a preset with no EXPECTED entry, or leaving an entry for a preset
    // that was removed, fails here — so a new capability fixture cannot land
    // uncounted.
    expect(Object.keys(EXPECTED).sort()).toEqual(CAPABILITY_FIXTURES.map((one) => one.id).sort());
  });

  it.each(CAPABILITY_FIXTURES.map((one) => one.id))('%s costs exactly what decision 9 counts', (id: string) => {
    expect(cost(corpusFrame(id), SIZE)).toEqual(EXPECTED[id]);
  });
});
